// 텍스트에서 매칭되는 지명 후보를 전부 찾아 [이름 길이, 시작 위치, 끝 위치, 결과 문자열, 매칭된 이름] 배열로 반환한다.
// findRegionInText와 findAllRegionMatches가 이 후보 목록을 공유한다.
function collectRegionCandidates(haystack) {
  const candidates = [];
  for (const [name, [sido, sigungu]] of Object.entries(SIGUNGU)) {
    const idx = haystack.lastIndexOf(name);
    if (idx >= 0) candidates.push([name.length, idx, idx + name.length, `${sido} ${sigungu}`, name]);
  }
  for (const [name, sido] of Object.entries(SIDO)) {
    const idx = haystack.lastIndexOf(name);
    if (idx >= 0) candidates.push([name.length, idx, idx + name.length, sido, name]);
  }
  return candidates;
}

// 텍스트에서 지역명을 찾아 "시도 시군구" 문자열로 반환. 못 찾으면 null.
// 여러 지명이 언급되면 더 긴 이름을 우선하고, 길이가 같으면 텍스트 뒤쪽에 나온 것을 선택한다.
function findRegionInText(text) {
  if (!text) return null;
  const candidates = collectRegionCandidates(String(text));
  if (!candidates.length) return null;
  candidates.sort((a, b) => a[0] - b[0] || a[2] - b[2]);
  return candidates[candidates.length - 1][3];
}

// findRegionInText와 같은 사전으로 매칭되는 지명을 위치 정보까지 포함해 전부 반환한다.
// (추천 기능에서 "이 지명이 문장 속 누구의 위치를 가리키는지" 문맥을 판단할 때 위치가 필요해서 추가함)
function findAllRegionMatches(text) {
  if (!text) return [];
  return collectRegionCandidates(String(text)).map(([, index, endIndex, region, name]) => ({
    name,
    region,
    index,
    endIndex,
  }));
}

// 사전에 "{시도} {짧은이름}"처럼 공백 포함 조합 키로 등록된 항목은, 그 짧은이름 자체가 다른 지역과
// 동명이라 일부러 구분해둔 것이다(예: "경기도 광주" ↔ 그냥 "광주"=광주광역시). 이런 짧은이름은 문맥만으로
// 어느 지역인지 확신할 수 없으니, 짧은이름 -> 후보 지역 목록(Map)으로 미리 계산해둔다.
function buildAmbiguousBareNames() {
  const byName = new Map();
  for (const [name, [sido, sigungu]] of Object.entries(SIGUNGU)) byName.set(name, `${sido} ${sigungu}`);
  for (const [name, sido] of Object.entries(SIDO)) byName.set(name, sido);

  const ambiguous = new Map();
  for (const name of byName.keys()) {
    const spaceIdx = name.indexOf(' ');
    if (spaceIdx < 0) continue;
    const bareName = name.slice(spaceIdx + 1);
    if (!byName.has(bareName)) continue;
    const bareRegion = byName.get(bareName);
    const qualifiedRegion = byName.get(name);
    if (bareRegion === qualifiedRegion) continue;
    if (!ambiguous.has(bareName)) ambiguous.set(bareName, new Set());
    ambiguous.get(bareName).add(bareRegion);
    ambiguous.get(bareName).add(qualifiedRegion);
  }
  return ambiguous;
}
const AMBIGUOUS_BARE_NAMES = buildAmbiguousBareNames();

// 매칭에 쓰인 지명(name)이 동명이지역 짧은이름이면 후보 지역 목록을, 아니면 null을 반환한다.
function ambiguousRegionsFor(name) {
  const set = AMBIGUOUS_BARE_NAMES.get(name);
  return set ? [...set] : null;
}

module.exports = { findRegionInText, findAllRegionMatches, ambiguousRegionsFor };
