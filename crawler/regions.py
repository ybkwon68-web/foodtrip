def guess_region(*texts: str) -> str | None:
    """제목 등 텍스트에서 지역명을 찾아 '시도 시군구' 문자열로 반환. 못 찾으면 None.

    회차 제목이 여러 지명을 언급하는 경우(예: "동해로 운전해~! 삼척 밥상") 더 긴 이름을
    우선하고, 길이가 같으면 텍스트 뒤쪽에 나온 지명을 선택한다. "OO의 XX 밥상"처럼
    실제 방문지가 제목 끝쪽에 오는 경우가 대부분이라는 점에 기반한 휴리스틱이며,
    완벽하지 않으므로 결과는 항상 미검수 상태로 취급해야 한다.
    """
    haystack = " ".join(t for t in texts if t)

    candidates = []  # (이름 길이, 끝 위치, 결과 문자열)
    for name, (sido, sigungu) in SIGUNGU.items():
        idx = haystack.rfind(name)
        if idx >= 0:
            candidates.append((len(name), idx + len(name), f"{sido} {sigungu}"))
    for name, sido in SIDO.items():
        idx = haystack.rfind(name)
        if idx >= 0:
            candidates.append((len(name), idx + len(name), sido))

    if not candidates:
        return None
    candidates.sort(key=lambda c: (c[0], c[1]))
    return candidates[-1][2]
